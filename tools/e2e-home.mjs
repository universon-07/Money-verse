// Home screen and save slots. Run with the dev server up: node tools/e2e-home.mjs
import { chromium } from 'playwright'
const b = await chromium.launch()
const page = await (await b.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true })).newPage()
const errors = []
page.on('pageerror', (e) => errors.push(e.message))
const ok = (m) => console.log('ok  ', m)
const fail = (m) => { console.log('FAIL', m); process.exitCode = 1 }
const state = () => page.evaluate(() => JSON.parse(localStorage.getItem('money-mohalla-v2') || '{}').state || {})
const go = async () => { await page.goto('http://localhost:5173/'); await page.waitForTimeout(800) }
const newGame = async (name) => {
  await page.getByRole('button', { name: /^New game/ }).click()
  await page.getByLabel('Name this game').fill(name)
  await Promise.all([page.waitForNavigation(), page.getByRole('button', { name: /^Start/ }).click()])
  await page.waitForTimeout(800)
}
await go()
await page.evaluate(() => { localStorage.clear(); sessionStorage.clear() })
await go()
;(await page.getByRole('button', { name: /^Load game/ }).isDisabled()) ? ok('home: load disabled with no saves') : fail('load should be disabled')
await newGame('Alpha')
page.url().endsWith('/story') && (await page.getByText('College student').first().isVisible()) ? ok('new game opens on avatar choice') : fail('story should open on avatar choice')
await page.getByText('College student').first().click()
await page.getByRole('button', { name: /^Skip/ }).click()
await page.waitForTimeout(1000)
;(await state()).persona === 'college' ? ok('Alpha: persona saved') : fail('Alpha persona')
await page.waitForTimeout(4500) // autosave
await page.getByRole('button', { name: 'Settings' }).first().click()
await Promise.all([page.waitForNavigation(), page.getByRole('menuitem', { name: /Home/ }).click()])
await page.waitForTimeout(800)
await newGame('Beta')
;!(await state()).persona ? ok('Beta starts empty') : fail('Beta should start empty')
await page.getByText('Earning youth').first().click().catch(() => page.getByRole('radio').nth(1).click())
await page.getByRole('button', { name: /^Skip/ }).click()
await page.waitForTimeout(1000)
await page.waitForTimeout(4500)
await page.getByRole('button', { name: 'Settings' }).first().click()
await Promise.all([page.waitForNavigation(), page.getByRole('menuitem', { name: /Home/ }).click()])
await page.waitForTimeout(800)
await page.getByRole('button', { name: /^Load game/ }).click()
;(await page.getByText('Alpha').count()) && (await page.getByText('Beta').count()) ? ok('both saves listed') : fail('saves not listed')
await page.getByRole('button', { name: 'Rename' }).first().click()
await page.getByLabel('Name this game').fill('Beta renamed')
await page.getByRole('button', { name: 'Save' }).click()
;(await page.getByText('Beta renamed').count()) ? ok('rename works') : fail('rename')
await Promise.all([page.waitForNavigation(), page.locator('li', { hasText: 'Alpha' }).getByRole('button', { name: /^Play/ }).click()])
await page.waitForTimeout(1000)
;(await state()).persona === 'college' && page.url().endsWith('/') ? ok('loading Alpha restores college persona on the island') : fail('load Alpha')
errors.length ? fail('page errors: ' + errors.join(' | ')) : ok('no page errors')
await b.close()
